const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),c={};vm.createContext(c);
vm.runInContext(fs.readFileSync('vision/web/motion-filter.js','utf8')+fs.readFileSync('vision/web/stick.js','utf8'),c);
const move=(x,y)=>c.canStick({x,y},[.5,.5]);
assert.ok(c.stickKeys(move(.55,.5)).W,'former D becomes W');
assert.ok(c.stickKeys(move(.45,.5)).S,'former A becomes S');
assert.ok(c.stickKeys(move(.5,.55)).A,'former W becomes A');
assert.ok(c.stickKeys(move(.5,.45)).D,'former S becomes D');
assert.ok(Math.abs(move(.534,.5).y-1)<1e-8,'full travel within 3.4% frame');
let keys=c.stickKeys({x:.2,y:0});assert.ok(keys.D);keys=c.stickKeys({x:.15,y:0},keys);assert.ok(keys.D);assert.equal(c.stickKeys({x:.1,y:0},keys).D,false);
assert.ok(Object.values(c.stickKeys(null,keys,false)).every(v=>!v));
assert.ok(Object.values(c.stickKeys(move(.5,.5))).every(v=>!v));
assert.ok(c.stickKeys(move(.6,.6)).W&&c.stickKeys(move(.6,.6)).A);
assert.ok(Math.abs(Math.hypot(move(1,1).x,move(1,1).y)-1)<1e-8);
const state={};c.stickContinuity(state,{x:1,y:0},1000);
assert.equal(c.stickContinuity(state,null,1129).x,1);
assert.ok(Math.abs(c.stickContinuity(state,null,1215).x-.5)<1e-8);
assert.equal(c.stickContinuity(state,null,1300),null);
c.stickContinuity(state,{x:1,y:0},1400,1000);assert.equal(c.stickContinuity(state,null,1400),null,'cached samples never extend hold');
assert.equal(c.stickContinuity(state,{x:0,y:1},1410).y,1,'reacquisition resumes immediately');
const input={},side={observation:{object_id:'one'},skeleton:{base_px:[0,100],top_px:[0,0],projected_lean_degrees:4}};
assert.equal(c.tiltStick(input,side,1000),0,'tilt saves neutral');side.skeleton.projected_lean_degrees=16;assert.ok(c.tiltStick(input,side,1100)>0);
side.skeleton.base_px=[80,100];assert.equal(c.tiltStick(input,side,1200),null,'moving base rejects tilt');
let k=c.stickKeys({x:Math.sin(.17),y:Math.cos(.17)});assert.deepEqual({...k},{W:true,A:false,S:false,D:false});
for(const deg of [20,25,30,32,24,31,22.6]){const a=deg*Math.PI/180;k=c.stickKeys({x:Math.sin(a),y:Math.cos(a)},k);assert.ok(k.W&&!k.D,'no flicker near the 22.5 deg edge: '+deg);}
k=c.stickKeys({x:Math.sin(33*Math.PI/180),y:Math.cos(33*Math.PI/180)},k);assert.ok(k.W&&k.D,'diagonal after the hysteresis band');
console.log('Stick checks passed: corrected axes, small travel, hysteresis, bounded gap decay, reacquisition and stable-base tilt.');
